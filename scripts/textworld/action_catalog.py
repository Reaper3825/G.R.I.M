"""Export the installed TextWorld action rules; no GRIM execution semantics here.

Run with --header PATH inside the existing TextWorld image to refresh the native
offline catalog. The runtime uses the same exporter to detect stale snapshots.
"""
import argparse
import json
import string
from pathlib import Path


def action_catalog():
    import textworld
    from textworld.generator.data import KnowledgeBase

    kb = KnowledgeBase.default()
    actions = []
    for name, rule in sorted(kb.rules.items()):
        command = kb.inform7_commands.get(name)
        if not command:
            continue
        placeholders = {p.name: p.type for p in rule.placeholders}
        parameters = []
        for _, field, _, _ in string.Formatter().parse(command):
            if field and field not in [p["name"] for p in parameters]:
                parameters.append({"name": field, "type": placeholders[field]})
        actions.append({"id": name, "command": command, "parameters": parameters,
                        "requires": sorted(str(p) for p in rule.preconditions),
                        "adds": sorted(str(p) for p in rule.added),
                        "removes": sorted(str(p) for p in rule.removed)})
    return {"version": 1, "textworld_version": textworld.__version__, "actions": actions}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    data = json.dumps(action_catalog(), indent=2, sort_keys=True)
    if args.header:
        args.header.write_text(
            '// Generated by scripts/textworld/action_catalog.py; do not edit.\n'
            '#pragma once\nnamespace GRIM::WorldLab {\n'
            'inline constexpr char kTextWorldActionCatalog[] = R"catalog(' + data +
            ')catalog";\n}\n', encoding="utf-8")
    else:
        print(data)
